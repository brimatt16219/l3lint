using System.Globalization;
using System.Text;
using L3Lint.Core;
using L3Lint.Core.Engine;
using L3Lint.Core.Model;
using L3Lint.Core.Rules;
using L3Lint.Hosting;
using L3Lint.Reporting.Rules;

namespace L3Lint.DocsGen;

/// <summary>
/// Writes one reference page per rule (FR-036) with the same renderer <c>l3lint explain</c> uses, plus the rule
/// index and the rules table of contents. Pages land at docs/rules/{id}.md because findings link to
/// rules/{id}.html (EngineInfo.RuleHelpUri).
/// </summary>
internal static class RuleDocs
{
    private const string Folder = "docs/rules";

    private static readonly (CardBrand? Brand, string Name)[] Groups =
    [
        (null, "General (all brands)"),
        (CardBrand.Visa, "Visa"),
        (CardBrand.Mastercard, "Mastercard"),
        (CardBrand.Amex, "American Express"),
        (CardBrand.Discover, "Discover"),
    ];

    public static void Generate(GeneratedFiles files)
    {
        var linter = L3LintFactory.CreateBuilder().Build();
        var rules = linter.Rules();
        var diagnostics = EngineDiagnostics.All
            .Select(d => linter.TryGetRule(d.Id, out var rule) ? rule : null)
            .OfType<RuleMetadata>()
            .OrderBy(r => r.Id, StringComparer.Ordinal)
            .ToList();

        files.Own(Folder, "*.md");
        foreach (var rule in rules.Concat(diagnostics))
        {
            Validate(files, rule);
            files.Add($"{Folder}/{rule.Id}.md", RuleMarkdown.Render(rule));
        }

        var packs = linter.RulePacks.ToDictionary(p => p.Id, StringComparer.Ordinal);
        var grouped = Groups
            .Select(g => (g.Name, Packs: packs.Values.Where(p => p.Brand == g.Brand).OrderBy(p => p.Id, StringComparer.Ordinal).ToList()))
            .Where(g => g.Packs.Count > 0)
            .ToList();
        var listed = grouped.SelectMany(g => g.Packs).Select(p => p.Id).ToHashSet(StringComparer.Ordinal);
        foreach (var pack in packs.Values.Where(p => !listed.Contains(p.Id)))
        {
            files.Problem($"rule pack {pack.Id} has no group in the rule index");
        }

        files.Add($"{Folder}/index.md", Index(rules, diagnostics, grouped));
        files.Add($"{Folder}/toc.yml", Toc(rules, diagnostics, grouped));
    }

    private static void Validate(GeneratedFiles files, RuleMetadata rule)
    {
        if (string.IsNullOrWhiteSpace(rule.Title))
        {
            files.Problem($"rule {rule.Id} has no title");
        }

        if (string.IsNullOrWhiteSpace(rule.Requirement))
        {
            files.Problem($"rule {rule.Id} has no requirement");
        }

        if (string.IsNullOrWhiteSpace(rule.Message))
        {
            files.Problem($"rule {rule.Id} has no message");
        }

        if (string.IsNullOrWhiteSpace(rule.Fix))
        {
            files.Problem($"rule {rule.Id} has no fix");
        }

        if (rule.Sources.Count == 0)
        {
            files.Problem($"rule {rule.Id} has no source");
        }
    }

    private static string Index(IReadOnlyList<RuleMetadata> rules, List<RuleMetadata> diagnostics, List<(string Name, List<RulePackInfo> Packs)> groups)
    {
        var page = new StringBuilder();
        page.Append("# Rule reference\n\n");
        page.Append("<!-- Generated by tools/L3Lint.DocsGen from the shipped rule packs. Do not edit by hand. -->\n\n");
        page.Append(CultureInfo.InvariantCulture, $"l3lint ships {rules.Count} rules in {groups.Sum(g => g.Packs.Count)} rule packs. ");
        page.Append("Each rule has its own page with the requirement, the reason, the check, the fix, its public sources and a passing and a failing example. ");
        page.Append("`l3lint explain <ruleId>` prints the same page in a terminal.\n\n");
        page.Append("Findings are advisory. A finding says a payload is likely to downgrade or misses a documented requirement; ");
        page.Append("a clean result says the payload meets the documented requirements l3lint checks. Card networks and issuers decide the rate. ");
        page.Append("See [Rules, severity and confidence](../articles/rules.md) for how to read the columns below.\n\n");

        foreach (var (name, packs) in groups)
        {
            page.Append("## ").Append(name).Append("\n\n");
            foreach (var pack in packs)
            {
                var count = rules.Count(r => r.PackId == pack.Id);
                page.Append(CultureInfo.InvariantCulture, $"Pack `{pack.Id}` version {pack.Version}, published {RuleText.Date(pack.PublishedOn)}, {count} rules.\n\n");
                Table(page, rules.Where(r => r.PackId == pack.Id));
            }
        }

        if (diagnostics.Count > 0)
        {
            page.Append("## Engine diagnostics\n\n");
            page.Append("The engine raises these findings itself. They are not part of any rule pack and do not count toward the ");
            page.Append(rules.Count.ToString(CultureInfo.InvariantCulture)).Append(" catalog rules.\n\n");
            Table(page, diagnostics);
        }

        return page.ToString();
    }

    private static void Table(StringBuilder page, IEnumerable<RuleMetadata> rules)
    {
        page.Append("| Rule | Title | Severity | Level | Confidence | Effective |\n| --- | --- | --- | --- | --- | --- |\n");
        foreach (var rule in rules)
        {
            page.Append("| [").Append(rule.Id).Append("](").Append(rule.Id).Append(".md) | ")
                .Append(Markdown.Cell(rule.Title)).Append(" | ")
                .Append(WireNames.Of(rule.Severity)).Append(" | ")
                .Append(WireNames.Of(rule.Level)).Append(" | ")
                .Append(WireNames.Of(rule.Confidence)).Append(" | ")
                .Append(Markdown.Cell(RuleText.Effective(rule))).Append(" |\n");
        }

        page.Append('\n');
    }

    private static string Toc(IReadOnlyList<RuleMetadata> rules, List<RuleMetadata> diagnostics, List<(string Name, List<RulePackInfo> Packs)> groups)
    {
        var toc = new StringBuilder();
        toc.Append("# Generated by tools/L3Lint.DocsGen. Do not edit by hand.\n");
        toc.Append("- name: Rule index\n  href: index.md\n");
        foreach (var (name, packs) in groups)
        {
            Items(toc, name, rules.Where(r => packs.Any(p => p.Id == r.PackId)));
        }

        if (diagnostics.Count > 0)
        {
            Items(toc, "Engine diagnostics", diagnostics);
        }

        return toc.ToString();
    }

    private static void Items(StringBuilder toc, string name, IEnumerable<RuleMetadata> rules)
    {
        toc.Append("- name: ").Append(Markdown.YamlString(name)).Append("\n  items:\n");
        foreach (var rule in rules)
        {
            toc.Append("  - name: ").Append(rule.Id).Append("\n    href: ").Append(rule.Id).Append(".md\n");
        }
    }
}
