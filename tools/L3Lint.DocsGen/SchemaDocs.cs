using System.Globalization;
using System.Text;
using System.Text.Json;
using System.Text.Json.Nodes;

namespace L3Lint.DocsGen;

/// <summary>
/// Writes the schema reference pages (results, config, canonical) from schemas/*.json, every property with its type,
/// constraints and description, nested objects as their own tables (NFR-014). Also copies every schema to
/// docs/schemas/ so the schemas' <c>$id</c> URLs resolve on the docs site.
/// </summary>
internal static class SchemaDocs
{
    private static readonly (string Schema, string Page, string Title, string Intro)[] Documented =
    [
        ("results", "docs/reference/results.md", "JSON results reference",
            "This is the shape of `l3lint lint --output json`, the contract for machines. The MCP tool `lint_payload` returns the same transaction and finding objects. "
            + "See [Output formats](../articles/output-formats.md) for the other formats and the exit codes."),
        ("config", "docs/reference/config.md", "Configuration file reference",
            "This is the shape of `.l3lint.yaml`. The file is YAML; the schema checks it after it is read, and an invalid file stops the run with exit code 3. "
            + "See [Configuration](../articles/configuration.md) for how the file is found and how its values combine with flags and the payload."),
        ("canonical", "docs/reference/canonical.md", "Canonical payload reference",
            "This is l3lint's own gateway-neutral payload. Lint it directly with `--format canonical`, or let an adapter build it from a gateway request "
            + "(see [Adapters and field mappings](../articles/adapters.md)). `l3lint convert <file> --to canonical` prints the canonical form of any supported input."),
    ];

    public static void Generate(GeneratedFiles files)
    {
        var root = Repository.Root();
        files.Own("docs/schemas", "*.json");
        foreach (var path in Directory.EnumerateFiles(Path.Combine(root, "schemas"), "*.schema.json").Order(StringComparer.Ordinal))
        {
            files.Add("docs/schemas/" + Path.GetFileName(path), File.ReadAllText(path));
        }

        foreach (var (schema, page, title, intro) in Documented)
        {
            var text = File.ReadAllText(Path.Combine(root, "schemas", schema + ".schema.json"));
            var node = JsonNode.Parse(text)?.AsObject() ?? throw new InvalidDataException(schema + " schema is empty");
            files.Add(page, new Renderer(files, schema, node).Render(title, intro));
        }
    }

    /// <summary>Renders one schema: a table for the root object, then one table per nested object.</summary>
    private sealed class Renderer(GeneratedFiles files, string name, JsonObject schema)
    {
        private readonly JsonObject _defs = schema["$defs"]?.AsObject() ?? [];
        private readonly Queue<Section> _pending = new();
        private List<Section> _children = [];
        private readonly Dictionary<string, Section> _defSections = new(StringComparer.Ordinal);
        private readonly HashSet<string> _anchors = new(StringComparer.Ordinal);
        private readonly bool _hasDefaults = schema.ToJsonString().Contains("\"default\":", StringComparison.Ordinal);

        public string Render(string title, string intro)
        {
            var page = new StringBuilder();
            page.Append("# ").Append(title).Append("\n\n");
            page.Append("<!-- Generated by tools/L3Lint.DocsGen from schemas/").Append(name).Append(".schema.json. Do not edit by hand. -->\n\n");
            page.Append(intro).Append("\n\n");
            page.Append("Schema: [").Append(name).Append(".schema.json](../schemas/").Append(name).Append(".schema.json) (JSON Schema draft 2020-12, `$id` ")
                .Append(Markdown.Code(Text(schema, "$id") ?? string.Empty)).Append("). `l3lint schema ").Append(name).Append("` prints the same file.\n\n");
            if (Text(schema, "description") is { } description)
            {
                page.Append(description).Append("\n\n");
            }

            page.Append("Types read \"string or null\" when a property may also be `null`. In the tables, an object that has its own table links to it.\n\n");
            // Inline objects follow their parent (depth first); shared $defs objects follow the whole tree.
            Write(page, new Section(Anchor("root"), "Root object", schema, Text(schema, "title"), ""));
            while (_pending.TryDequeue(out var section))
            {
                Write(page, section);
            }

            return page.ToString().TrimEnd('\n') + "\n";
        }

        private void Write(StringBuilder page, Section section)
        {
            var outer = _children;
            _children = [];
            page.Append("<a id=\"").Append(section.Anchor).Append("\"></a>\n\n");
            page.Append("## ").Append(section.Heading).Append("\n\n");
            if (section.Description is { } description && section.Heading != "Root object")
            {
                page.Append(Markdown.Cell(description)).Append("\n\n");
            }

            var properties = section.Schema["properties"]?.AsObject();
            var required = section.Schema["required"]?.AsArray().Select(r => r!.GetValue<string>()).ToHashSet(StringComparer.Ordinal) ?? [];
            if (properties is not null && properties.Count > 0)
            {
                page.Append(_hasDefaults
                    ? "| Property | Type | Required | Default | Constraints | Description |\n| --- | --- | --- | --- | --- | --- |\n"
                    : "| Property | Type | Required | Constraints | Description |\n| --- | --- | --- | --- | --- |\n");
                foreach (var (property, value) in properties)
                {
                    var propertySchema = value?.AsObject() ?? [];
                    var path = section.Path + "/" + property;
                    var info = Describe(propertySchema, Join(section.Display, property));
                    var text = Text(propertySchema, "description") ?? info.Description;
                    if (string.IsNullOrWhiteSpace(text))
                    {
                        files.Problem($"schema {name}: property {path} has no description");
                    }

                    page.Append("| ").Append(Markdown.Code(property)).Append(" | ")
                        .Append(info.Type).Append(" | ")
                        .Append(required.Contains(property) ? "yes" : "no").Append(" | ");
                    if (_hasDefaults)
                    {
                        page.Append(propertySchema["default"] is { } fallback ? Markdown.Code(Json(fallback)) : string.Empty).Append(" | ");
                    }

                    page.Append(string.Join("; ", info.Constraints)).Append(" | ")
                        .Append(Markdown.Cell(text)).Append(" |\n");
                }

                page.Append('\n');
            }

            if (section.Schema["additionalProperties"] is JsonValue closed && closed.GetValueKind() == JsonValueKind.False)
            {
                page.Append("No other properties are allowed.\n\n");
            }

            var children = _children;
            _children = outer;
            foreach (var child in children)
            {
                Write(page, child);
            }
        }

        /// <summary>Describes a schema as a type text and constraints, queuing a section for any object with properties.</summary>
        private Info Describe(JsonObject node, string display)
        {
            if (Text(node, "$ref") is { } reference)
            {
                var defName = reference.Split('/')[^1];
                var def = _defs[defName]?.AsObject() ?? throw new InvalidDataException($"{name}: unknown $ref {reference}");
                if (def["properties"] is not null)
                {
                    var section = DefSection(defName, def);
                    return new Info($"[{defName}](#{section.Anchor})", [], Text(def, "description"));
                }

                var inner = Describe(def, display);
                return inner with { Description = Text(def, "description") ?? inner.Description };
            }

            if ((node["oneOf"] ?? node["anyOf"]) is JsonArray alternatives)
            {
                var parts = alternatives.Select(n => Describe(n!.AsObject(), display)).ToList();
                return new Info(string.Join(" or ", parts.Select(p => p.Type)), [.. parts.SelectMany(p => p.Constraints).Distinct(StringComparer.Ordinal)], null);
            }

            var constraints = new List<string>();
            if (node["const"] is { } constant)
            {
                constraints.Add("always " + Markdown.Code(Json(constant)));
                return new Info(KindName(constant), constraints, null);
            }

            if (node["enum"] is JsonArray values)
            {
                var kinds = values.Select(v => v is null ? "null" : KindName(v)).Distinct(StringComparer.Ordinal).OrderBy(k => k == "null" ? 1 : 0).ToList();
                constraints.Add("one of " + string.Join(", ", values.Where(v => v is not null).Select(v => Markdown.Code(Json(v!)))));
                return new Info(string.Join(" or ", kinds), constraints, null);
            }

            var types = node["type"] switch
            {
                JsonArray list => list.Select(t => t!.GetValue<string>()).ToList(),
                JsonValue single => [single.GetValue<string>()],
                _ => node["properties"] is not null || node["additionalProperties"] is JsonObject ? ["object"] : [],
            };
            if (types.Count == 0)
            {
                return new Info("any JSON value", constraints, null);
            }

            var typeTexts = new List<string>();
            foreach (var type in types.OrderBy(t => t == "null" ? 1 : 0))
            {
                switch (type)
                {
                    case "object" when node["properties"] is not null:
                        var section = Enqueue(display, node);
                        typeTexts.Add($"object, see [{section.Heading}](#{section.Anchor})");
                        break;
                    case "object" when node["additionalProperties"] is JsonObject values2:
                        var value = Describe(values2, display + ".*");
                        typeTexts.Add("map of " + KeyText(node) + " to " + value.Type);
                        constraints.AddRange(value.Constraints.Select(c => "values: " + c));
                        break;
                    case "array" when node["items"] is JsonObject items:
                        var item = Describe(items, display + "[]");
                        typeTexts.Add("array of " + item.Type);
                        constraints.AddRange(item.Constraints.Select(c => "items: " + c));
                        break;
                    default:
                        typeTexts.Add(type);
                        break;
                }
            }

            AddConstraints(node, constraints);
            return new Info(string.Join(" or ", typeTexts), constraints, null);
        }

        private static string KeyText(JsonObject node) => node["propertyNames"] switch
        {
            JsonObject names when Text(names, "pattern") is { } pattern => "keys matching " + Markdown.Code(pattern),
            JsonObject names when names["enum"] is JsonArray keys => "keys (" + string.Join(", ", keys.Select(k => Markdown.Code(k!.GetValue<string>()))) + ")",
            _ => "string keys",
        };

        private static void AddConstraints(JsonObject node, List<string> constraints)
        {
            Add("minimum", "at least {0}");
            Add("exclusiveMinimum", "greater than {0}");
            Add("maximum", "at most {0}");
            Add("exclusiveMaximum", "less than {0}");
            Add("minLength", "at least {0} character{1}");
            Add("maxLength", "at most {0} character{1}");
            Add("minItems", "at least {0} item{1}");
            Add("maxItems", "at most {0} item{1}");
            Add("multipleOf", "a multiple of {0}");
            if (Text(node, "pattern") is { } pattern)
            {
                constraints.Add("pattern " + Markdown.Code(pattern));
            }

            if (Text(node, "format") is { } format)
            {
                constraints.Add("format " + Markdown.Code(format));
            }

            void Add(string keyword, string template)
            {
                if (node[keyword] is JsonValue value)
                {
                    var text = Json(value);
                    constraints.Add(string.Format(CultureInfo.InvariantCulture, template, text, text == "1" ? string.Empty : "s"));
                }
            }
        }

        private Section DefSection(string defName, JsonObject def)
        {
            if (!_defSections.TryGetValue(defName, out var section))
            {
                section = new Section(Anchor(defName), defName, def, Text(def, "description"), "/$defs/" + defName);
                _defSections[defName] = section;
                _pending.Enqueue(section);
            }

            return section;
        }

        private Section Enqueue(string display, JsonObject node)
        {
            var section = new Section(Anchor(display), display, node, Text(node, "description"), "/" + display.Replace('.', '/'));
            _children.Add(section);
            return section;
        }

        private string Anchor(string display)
        {
            var slug = new string([.. display.ToLowerInvariant().Select(c => char.IsAsciiLetterOrDigit(c) ? c : '-')]).Trim('-');
            while (slug.Contains("--", StringComparison.Ordinal))
            {
                slug = slug.Replace("--", "-", StringComparison.Ordinal);
            }

            var anchor = "schema-" + slug;
            for (var n = 2; !_anchors.Add(anchor); n++)
            {
                anchor = "schema-" + slug + "-" + n.ToString(CultureInfo.InvariantCulture);
            }

            return anchor;
        }

        private static string Join(string parent, string property) => parent.Length == 0 ? property : parent + "." + property;

        private static string KindName(JsonNode value) => value.GetValueKind() switch
        {
            JsonValueKind.String => "string",
            JsonValueKind.Number => value.ToJsonString().Contains('.', StringComparison.Ordinal) ? "number" : "integer",
            JsonValueKind.True or JsonValueKind.False => "boolean",
            JsonValueKind.Array => "array",
            JsonValueKind.Object => "object",
            _ => "null",
        };

        private static string Json(JsonNode value) =>
            value.GetValueKind() == JsonValueKind.String ? value.GetValue<string>() : value.ToJsonString();

        private static string? Text(JsonObject node, string key) =>
            node[key] is JsonValue value && value.GetValueKind() == JsonValueKind.String ? value.GetValue<string>() : null;
    }

    private sealed record Section(string Anchor, string Heading, JsonObject Schema, string? Description, string Path)
    {
        public string Display => Heading == "Root object" ? string.Empty : Heading;
    }

    private sealed record Info(string Type, List<string> Constraints, string? Description);
}
